#[macroquad::main(window_conf)]
async fn main() {
    // MB_ROOT points at the project (assets and original/) when the game
    // starts from elsewhere, as an .app bundle does.
    if let Some(root) = std::env::var_os("MB_ROOT") {
        let _ = std::env::set_current_dir(root);
    }
    let ui = load_ui_set().await;
    let menu_assets = load_menu_assets().await;
    let play_assets = load_play_assets().await;
    let pause_assets = load_pause_assets().await;
    let music = load_sound("original/audio/music.wav").await.unwrap();
    let mut sounds: Vec<Option<Sound>> = vec![None];
    for id in 1..=SOUND_COUNT {
        sounds.push(Some(
            load_sound(&format!("original/audio/sound_{:02}.wav", id))
                .await
                .unwrap(),
        ));
    }
    // An effect does not restart within EFFECT_GAP of its last start, so a
    // burst (30 rings collected at once) plays once instead of stacking
    // into one very loud sound.
    let last_played: Vec<std::cell::Cell<f64>> =
        (0..=SOUND_COUNT).map(|_| std::cell::Cell::new(f64::NEG_INFINITY)).collect();
    let play_effect = |id: usize, volume: f32| {
        let now = get_time();
        if let Some(last) = last_played.get(id) {
            if now - last.get() < EFFECT_GAP {
                return;
            }
            last.set(now);
        }
        if let Some(Some(sound)) = sounds.get(id) {
            play_sound(
                sound,
                PlaySoundParams {
                    looped: false,
                    volume,
                },
            );
        }
    };
    let canvas = Canvas::new();
    let mut backdrop = MenuBackdrop::new();
    let mut progress = Progress::load();
    let mut scores = Scores::load();
    let mut settings = Settings::load();
    // MB_DUMP_SETTINGS prints the loaded settings and exits, for checking
    // persistence without a GUI.
    if std::env::var_os("MB_DUMP_SETTINGS").is_some() {
        eprintln!("settings: {}", settings.to_text().replace('\n', " "));
        std::process::exit(0);
    }

    if settings.fullscreen {
        set_fullscreen(true);
    }
    bindings::install(bindings::Bindings::load());

    let mut screen = Screen::Menu(MenuKind::Main);
    let mut menu_screen = build_menu(MenuKind::Main, &ui, &progress, true);
    let mut menu_next: Option<Next> = None;
    let mut game: Option<Play> = None;
    let mut pause: Option<Pause> = None;
    let mut pending: Option<PendingRun> = None;
    // Where a game that opened with the tutorial goes once it ends.
    let mut after_tutorial: Option<Next> = None;
    let mut music_on = false;
    let mut frame_count: u32 = 0;
    // MB_START=<world>.<stage> (1-based, world 7 = survival) boots straight
    // into a stage, for scripted frame comparisons.
    if let Some((w, s)) = std::env::var("MB_START").ok().and_then(|v| {
        let (w, s) = v.split_once('.')?;
        Some((w.parse::<usize>().ok()?, s.parse::<usize>().ok()?))
    }) {
        game = Some(Play::new(
            w.saturating_sub(1).min(SURVIVAL),
            s,
            progress.best,
            &play_assets,
        ));
        screen = Screen::Game;
    }
    // MB_MENU=<main|mode|options|controls|scores|scores-*|name> opens a
    // screen directly.
    if let Ok(name) = std::env::var("MB_MENU") {
        game = None;
        if name == "name" {
            screen = Screen::NameEntry(NameEntry::new(22410));
        } else if name == "options" || name == "controls" || name == "help" {
            let page = if name == "options" { OptionsPage::Main } else { OptionsPage::Controls };
            screen = Screen::Options(Options::new(page));
        } else {
            let kind = match name.as_str() {
                "mode" => MenuKind::Mode,
                "scores" => MenuKind::ScoresSelect,
                "scores-arcade" => MenuKind::ScoresTable(0, false),
                "scores-survival" => MenuKind::ScoresTable(1, false),
                "scores-global" => MenuKind::ScoresTable(0, true),
                "main" => MenuKind::Main,
                "world" => MenuKind::World,
                "stage" => MenuKind::Stage(0),
                _ => MenuKind::Main,
            };
            screen = Screen::Menu(kind);
            menu_screen = build_menu(kind, &ui, &progress, true);
            // MB_FOCUS=<n> shows the controller focus frame in captures.
            if let Ok(v) = std::env::var("MB_FOCUS") {
                if let Ok(i) = v.parse::<usize>() {
                    menu_screen.set_focus(Some(i));
                }
            }
        }
    }
    // MB_TUTORIAL=<step> runs the tutorial from that step (0 = the start),
    // then World 1 Stage 1.
    if let Some(step) = std::env::var("MB_TUTORIAL").ok().and_then(|v| v.parse().ok()) {
        game = Some(Play::tutorial(progress.best, &play_assets, Tutorial::start_at(step)));
        after_tutorial = Some(Next::Game(0, 1));
        screen = Screen::Game;
    }
    // MB_PAUSE opens a popup for screenshot runs.
    if let Ok(kind) = std::env::var("MB_PAUSE") {
        pause = Some(match kind.as_str() {
            "upgrade" => Pause::menu_page(Page::Upgrade),
            "clear" => Pause::results(true, 0, 1, 12345, 2, 42.0, 108.0),
            "gameover" => Pause::results(false, 0, 1, 12345, 2, 42.0, 0.0),
            "controls" => Pause::menu_page(Page::Controls),
            _ => Pause::menu(),
        });
    }
    // The popup only draws on the game screen; start a stage when MB_START
    // (or MB_MENU) did not, so MB_PAUSE captures the popup itself.
    if pause.is_some() && game.is_none() {
        game = Some(Play::new(0, 1, progress.best, &play_assets));
        screen = Screen::Game;
    }

    // MB_PROF prints update and draw CPU time per window; MB_PROF_FRAMES=N
    // exits after N frames, for unattended benchmarks.
    let prof = std::env::var_os("MB_PROF").is_some();
    let prof_frames: u32 = std::env::var("MB_PROF_FRAMES")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(0);
    let mut prof_update = 0.0f64;
    let mut prof_draw = 0.0f64;
    let mut prof_max_update = 0.0f64;
    let mut prof_max_draw = 0.0f64;
    let mut prof_dt = 0.0f64;
    let mut prof_window = 0u32;
    // Read once: env lookups take the process environment lock.
    let shot_frame: u32 = std::env::var("MB_SHOT_FRAME")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(20);
    let shot_path = std::env::var("MB_SHOT").ok();
    let auto_name = std::env::var("MB_NAME").ok();
    // The simulation runs at the original's 60 Hz; frames are drawn at the
    // Options frame-rate cap (60, 120 or 144), blending between steps.
    // miniquad's display-link pacing is not reliable (an occluded or
    // unfocused window can run the loop uncapped and peg a core), so pace it
    // here; vsync still holds it to the display's refresh. MB_FPS overrides
    // the cap (0 = uncapped, for benchmarks). Screenshot runs stay uncapped
    // unless MB_FPS is given, so MB_SHOT_FRAME keeps selecting the same
    // simulation state as before pacing existed.
    #[cfg(not(target_arch = "wasm32"))]
    let fps_override: Option<f64> = std::env::var("MB_FPS")
        .ok()
        .and_then(|v| v.parse().ok())
        .or(if shot_path.is_some() { Some(0.0) } else { None });
    #[cfg(not(target_arch = "wasm32"))]
    let mut next_deadline = Instant::now();

    loop {
        let dt = get_frame_time().min(0.05);
        let t0 = get_time();
        pad::poll();
        // F11 or Alt+Enter toggles fullscreen, remembered across launches.
        let alt = is_key_down(KeyCode::LeftAlt) || is_key_down(KeyCode::RightAlt);
        if is_key_pressed(KeyCode::F11) || (alt && is_key_pressed(KeyCode::Enter)) {
            settings.fullscreen = !settings.fullscreen;
            set_fullscreen(settings.fullscreen);
            settings.save();
        }
        if music_on {
            set_sound_volume(&music, settings.music);
        }

        // `labelEnterName`: Enter files the run and opens its results popup;
        // Escape skips and the table keeps the default name.
        let mut confirmed: Option<String> = None;
        if let Screen::NameEntry(ref mut entry) = screen {
            if let Some(name) = &auto_name {
                // MB_NAME=<name> confirms the field for scripted runs.
                entry.name = name.clone();
                confirmed = Some(entry.name.clone());
            } else if entry.update() {
                confirmed = Some(entry.name.clone());
            }
        }
        if let Some(name) = confirmed {
            eprintln!("name entry confirmed: {:?}", name);
            if let Some(run) = pending.take() {
                scores.insert(run.survival, &scores::sanitize(&name), run.score);
                scores.save();
                pause = Some(Pause::results(
                    run.cleared,
                    run.world,
                    run.stage,
                    run.score,
                    run.multiplier,
                    run.time,
                    run.bonus,
                ));
            }
            screen = Screen::Game;
        }

        match screen {
            Screen::Menu(kind) => {
                backdrop.update(dt);
                // A controller's B goes back, like each menu's back button.
                let back = match kind {
                    MenuKind::Mode => Some(2),
                    MenuKind::World => Some(7),
                    MenuKind::Stage(_) => Some(6),
                    MenuKind::ScoresSelect => Some(2),
                    MenuKind::ScoresTable(..) => Some(6),
                    MenuKind::Main => None,
                };
                let pad_back = back.filter(|_| {
                    menu_screen.fx.ready() && menu_next.is_none() && pad::pressed(pad::Button::B)
                });
                if let Some(event) = menu_screen.update(dt).or(pad_back) {
                    play_effect(SOUND_BUTTON, settings.effects);
                    if let Some(next) = menu_event(kind, event) {
                        menu_next = Some(next);
                        menu_screen.fx.leave();
                    }
                }
                if kind == MenuKind::Main
                    && menu_screen.fx.ready()
                    && (pad::enter_pressed() || pad::pressed(pad::Button::Start))
                {
                    menu_next = Some(Next::Menu(MenuKind::Mode));
                    menu_screen.fx.leave();
                }
                if menu_screen.fx.done() {
                    match menu_next.take() {
                        Some(Next::Menu(next)) => {
                            menu_screen = build_menu(next, &ui, &progress, false);
                            screen = Screen::Menu(next);
                        }
                        Some(Next::Game(world, stage)) => {
                            game = Some(if starts_with_tutorial(&settings, world, stage) {
                                after_tutorial = Some(Next::Game(world, stage));
                                Play::tutorial(progress.best, &play_assets, Tutorial::start())
                            } else {
                                Play::new(world, stage, progress.best, &play_assets)
                            });
                            screen = Screen::Game;
                            if !music_on {
                                play_sound(
                                    &music,
                                    PlaySoundParams {
                                        looped: true,
                                        volume: settings.music,
                                    },
                                );
                                music_on = true;
                            }
                        }
                        Some(Next::Options(page)) => screen = Screen::Options(Options::new(page)),
                        None => menu_screen = build_menu(kind, &ui, &progress, false),
                    }
                }
            }
            Screen::Options(ref mut options) => {
                backdrop.update(dt);
                let before = settings;
                let outcome = options.update(dt, &mut settings);
                if settings != before {
                    settings.save();
                }
                match outcome {
                    Some(OptionsOutcome::Click) => play_effect(SOUND_BUTTON, settings.effects),
                    Some(OptionsOutcome::Close) => {
                        play_effect(SOUND_BUTTON, settings.effects);
                        menu_screen = build_menu(MenuKind::Main, &ui, &progress, false);
                        screen = Screen::Menu(MenuKind::Main);
                    }
                    None => {}
                }
            }
            Screen::Game => {
                if pause.is_some() {
                    let before = settings;
                    let action = match (pause.as_mut(), game.as_mut()) {
                        (Some(p), Some(g)) => p.update(dt, g, &mut settings),
                        _ => None,
                    };
                    // `PausePopup::save`: options are written through as soon
                    // as they change, not when the popup closes.
                    if settings != before {
                        settings.save();
                    }
                    match action {
                        Some(Action::Resume) => pause = None,
                        Some(Action::Leave) => {
                            let kind = match game.as_ref() {
                                Some(g) if g.world < SURVIVAL => MenuKind::Stage(g.world),
                                _ => MenuKind::Mode,
                            };
                            game = None;
                            pause = None;
                            after_tutorial = None;
                            stop_sound(&music);
                            music_on = false;
                            menu_screen = build_menu(kind, &ui, &progress, true);
                            screen = Screen::Menu(kind);
                        }
                        Some(Action::NextStage) => {
                            pause = None;
                            // `GameScreen::handleEvent` starts the next stage
                            // in the same screen, so the run's score, rings
                            // and upgrades stay.
                            let advanced = game
                                .as_mut()
                                .is_some_and(|g| g.advance_stage(&play_assets));
                            if !advanced {
                                let kind = match game.as_ref() {
                                    Some(g) if g.world < SURVIVAL => MenuKind::Stage(g.world),
                                    _ => MenuKind::Mode,
                                };
                                game = None;
                                stop_sound(&music);
                                music_on = false;
                                menu_screen = build_menu(kind, &ui, &progress, true);
                                screen = Screen::Menu(kind);
                            }
                        }
                        None => {}
                    }
                    if let Some(g) = game.as_mut() {
                        for id in g.sounds.drain(..) {
                            play_effect(id, settings.effects);
                        }
                    }
                } else if let Some(g) = game.as_mut() {
                    g.set_shake_scale(settings.shake);
                    g.update(dt);
                    for id in g.sounds.drain(..) {
                        play_effect(id, settings.effects);
                    }
                    if g.tutorial_complete() {
                        // WaveManager::isStageComplete for level 7: go on
                        // to the game the tutorial was opened for.
                        if let Some(Next::Game(world, stage)) = after_tutorial.take() {
                            *g = Play::new(world, stage, progress.best, &play_assets);
                        } else {
                            game = None;
                            stop_sound(&music);
                            music_on = false;
                            menu_screen = build_menu(MenuKind::Main, &ui, &progress, true);
                            screen = Screen::Menu(MenuKind::Main);
                        }
                    } else if let Some(cleared) = g.result() {
                        let run = PendingRun {
                            cleared,
                            world: g.world,
                            stage: g.stage,
                            score: g.score,
                            multiplier: g.multiplier,
                            time: g.stage_time(),
                            bonus: g.time_bonus(),
                            survival: g.world == SURVIVAL,
                        };
                        if g.world < SURVIVAL {
                            progress.unlocked = progress.unlocked.max(g.world * 5 + g.stage);
                            progress.best = progress.best.max(g.score);
                            progress.save();
                        }
                        // MB_AUTONEXT=1: scripted runs skip the results and
                        // upgrade popups and advance at once, to check what
                        // carries into the next stage. The last stage keeps
                        // the normal results path.
                        let auto_next = std::env::var_os("MB_AUTONEXT").is_some()
                            && run.cleared
                            && game.as_ref().is_some_and(|g| g.next_stage().is_some());
                        if auto_next {
                            if let Some(g) = game.as_mut() {
                                // MB_BUY=<index> buys one upgrade before the
                                // advance, to check that purchases carry.
                                if let Some(u) = std::env::var("MB_BUY")
                                    .ok()
                                    .and_then(|v| v.parse::<usize>().ok())
                                    .and_then(|n| UPGRADES.get(n).copied())
                                {
                                    g.upgrade_points += 1000;
                                    g.buy_upgrade(u);
                                }
                                g.apply_time_bonus(run.bonus);
                                let advanced = g.advance_stage(&play_assets);
                                eprintln!(
                                    "advance: ok {} world {} stage {} score {} rings {} points {} upgrades {:?}",
                                    advanced,
                                    g.world,
                                    g.stage,
                                    g.score,
                                    g.rings,
                                    g.upgrade_points,
                                    g.upgrade_levels()
                                );
                                if advanced {
                                    pause = None;
                                } else {
                                    pause = Some(Pause::results(
                                        run.cleared,
                                        run.world,
                                        run.stage,
                                        run.score,
                                        run.multiplier,
                                        run.time,
                                        run.bonus,
                                    ));
                                }
                            }
                        } else if {
                            // The name step belongs to the end of a run, not
                            // to a stage clear that continues. Asking after
                            // every stage interrupted the run mid-play.
                            let run_ends = !run.cleared
                                || game.as_ref().is_some_and(|g| g.next_stage().is_none());
                            run_ends && scores.qualifies(run.survival, run.score)
                        } {
                            screen = Screen::NameEntry(NameEntry::new(run.score));
                            pending = Some(run);
                        } else {
                            pause = Some(Pause::results(
                                run.cleared,
                                run.world,
                                run.stage,
                                run.score,
                                run.multiplier,
                                run.time,
                                run.bonus,
                            ));
                        }
                    } else {
                        let pad_pause = bindings::pressed(bindings::Action::Pause);
                        let icon = Rect::new(449.0 + gfx::edge(), -1.0, 32.0, 22.0);
                        let clicked = is_mouse_button_pressed(MouseButton::Left)
                            && icon.contains(Canvas::mouse());
                        if (is_key_pressed(KeyCode::Escape) || pad_pause || clicked) && g.can_pause() {
                            pause = Some(Pause::menu());
                        }
                    }
                }
            }
            Screen::NameEntry(_) => {}
        }

        let t1 = get_time();

        gfx::set_widescreen(settings.widescreen);
        canvas.begin();
        // The glow comes from the world's emitters; a popup hides them.
        canvas.set_bloom(settings.bloom && pause.is_none());
        match screen {
            Screen::Menu(kind) => {
                menu_screen.draw(&canvas, &menu_assets, &backdrop);
                if let MenuKind::ScoresTable(mode, global) = kind {
                    scores::draw_rows(
                        &play_assets.hud.font,
                        &scores,
                        mode == 1,
                        global,
                        menu_screen.fx.alpha,
                    );
                }
            }
            Screen::Game => {
                if let Some(g) = game.as_ref() {
                    g.draw(&canvas, &play_assets);
                    if let Some(p) = pause.as_ref() {
                        p.draw(&canvas, &pause_assets, g, &settings);
                    }
                }
            }
            Screen::NameEntry(ref entry) => entry.draw(
                &canvas,
                &menu_assets,
                &backdrop,
                &ui["labelEnterName"],
                &play_assets.hud.font,
            ),
            Screen::Options(ref options) => {
                backdrop.draw(&canvas, &menu_assets, 1.0);
                options.draw(&canvas, &play_assets.hud.font, &settings);
            }
        }
        canvas.end();
        let t2 = get_time();

        if prof {
            let update_ms = (t1 - t0) * 1000.0;
            let draw_ms = (t2 - t1) * 1000.0;
            prof_update += update_ms;
            prof_draw += draw_ms;
            prof_max_update = prof_max_update.max(update_ms);
            prof_max_draw = prof_max_draw.max(draw_ms);
            prof_dt += dt as f64;
            prof_window += 1;
            if prof_window == 120 {
                let n = prof_window as f64;
                eprintln!(
                    "perf: update {:.2}ms avg / {:.2}ms max, draw {:.2}ms avg / {:.2}ms max, frame {:.2}ms ({:.1} fps)",
                    prof_update / n,
                    prof_max_update,
                    prof_draw / n,
                    prof_max_draw,
                    prof_dt * 1000.0 / n,
                    n / prof_dt
                );
                prof_update = 0.0;
                prof_draw = 0.0;
                prof_max_update = 0.0;
                prof_max_draw = 0.0;
                prof_dt = 0.0;
                prof_window = 0;
            }
        }

        // F12 saves the frame for pixel comparison against emulator frames;
        // MB_SHOT=<file> saves frame MB_SHOT_FRAME (default 20) there and exits.
        frame_count += 1;
        let auto_shot = shot_path.as_deref().filter(|_| frame_count == shot_frame);
        if auto_shot.is_some() {
            if let Some(g) = game.as_ref() {
                eprintln!("shot: ship at {:?} score {} mult {} bombs {} lives {}", g.ship_pos(), g.score, g.multiplier, g.bombs, g.lives);
            }
            eprintln!(
                "shot: pause {} name entry {}",
                pause.is_some(),
                matches!(screen, Screen::NameEntry(_))
            );
            if let Screen::NameEntry(ref entry) = screen {
                eprintln!("shot: name buffer {:?}", entry.name);
            }
        }
        if is_key_pressed(KeyCode::F12) || auto_shot.is_some() {
            let _ = std::fs::create_dir_all("shots");
            let name = auto_shot
                .map(str::to_owned)
                .unwrap_or_else(|| format!("shots/port_{}.png", (get_time() * 1000.0) as u64));
            get_screen_data().export_png(&name);
            if auto_shot.is_some() {
                std::process::exit(0);
            }
        }
        if prof && prof_frames > 0 && frame_count >= prof_frames {
            if let Some(g) = game.as_ref() {
                eprintln!(
                    "perf: end score {} rings {} ship {:?}",
                    g.score,
                    g.rings,
                    g.ship_pos()
                );
            }
            if prof_window > 0 {
                let n = prof_window as f64;
                eprintln!(
                    "perf: final update {:.2}ms avg / {:.2}ms max, draw {:.2}ms avg / {:.2}ms max, frame {:.2}ms",
                    prof_update / n,
                    prof_max_update,
                    prof_draw / n,
                    prof_max_draw,
                    prof_dt * 1000.0 / n
                );
            }
            std::process::exit(0);
        }
        next_frame().await;
        #[cfg(not(target_arch = "wasm32"))]
        {
            let target_fps = fps_override.unwrap_or(settings.fps as f64);
            if target_fps > 0.0 {
                let period = Duration::from_secs_f64(1.0 / target_fps);
                next_deadline += period;
                let now = Instant::now();
                if next_deadline > now {
                    std::thread::sleep(next_deadline - now);
                } else if now.duration_since(next_deadline) > period {
                    // A long stall (window drag, shader compile): resynchronise
                    // instead of trying to catch up frame by frame.
                    next_deadline = now;
                }
            }
        }
    }
}
