fn window_conf() -> Conf {
    // MB_WINDOW=480x320 gives a 1:1 window for pixel comparisons with the
    // original's frames (the F12 export is then exactly 480x320).
    let (width, height, high_dpi) = match std::env::var("MB_WINDOW").ok().and_then(|v| {
        let (w, h) = v.split_once('x')?;
        Some((w.parse().ok()?, h.parse().ok()?))
    }) {
        Some((w, h)) => (w, h, false),
        None => (1280, 720, true),
    };
    Conf {
        window_title: "Meteor Blitz".to_owned(),
        window_width: width,
        window_height: height,
        high_dpi,
        window_resizable: true,
        sample_count: 4,
        ..Default::default()
    }
}

/// The original's menu screens, by `Director` screen id.
#[derive(Clone, Copy, PartialEq, Eq)]
enum MenuKind {
    /// MainMenuScreen (2)
    Main,
    /// PlayScreen (3): arcade or survival
    Mode,
    /// LevelSelectScreen (4): world
    World,
    /// StageSelectScreen (14): stage of `world`
    Stage(usize),
    /// HighScoresSelectScreen: arcade or survival scores.
    ScoresSelect,
    /// HighScoresScreen: the table for `mode` (0 arcade, 1 survival), local
    /// or global.
    ScoresTable(usize, bool),
}

/// sounds.raw holds effects 1-17 (music.raw is id 0).
const SOUND_COUNT: usize = 17;
/// Shortest time between two starts of the same effect, in seconds.
const EFFECT_GAP: f64 = 0.08;
/// Audio::play id for button presses.
const SOUND_BUTTON: usize = 9;

/// `Global::level` for survival (worlds are 0-5).
const SURVIVAL: usize = 6;

enum Screen {
    Menu(MenuKind),
    Game,
    /// `labelEnterName`: asked once a run qualifies for the local table.
    NameEntry(NameEntry),
    Options(Options),
}

/// A finished run waiting on the name step before its results popup.
struct PendingRun {
    cleared: bool,
    world: usize,
    stage: usize,
    score: u64,
    multiplier: u32,
    time: f32,
    bonus: f32,
    survival: bool,
}

/// Where a menu goes once its fade-out finishes.
#[derive(Clone, Copy)]
enum Next {
    Menu(MenuKind),
    /// World (or SURVIVAL) and stage.
    Game(usize, usize),
    Options(OptionsPage),
}

/// Menu art by file stem (`assets/ui/<name>.png`).
type Ui = HashMap<String, Texture2D>;

/// The art path: the 4x copy generated by `tools/upscale4x.py` when the HD
/// path is on (`MB_HD=0` selects the originals), else the original file.
/// The generated set is complete, so a missing copy is a setup error.
fn art_path(hd_rel: &str, original: &str) -> String {
    if gfx::asset_scale() > 1.0 {
        format!("assets/4x/{}", hd_rel)
    } else {
        original.to_owned()
    }
}

async fn load_ui(name: &str) -> Texture2D {
    let path = art_path(&format!("ui/{}.png", name), &format!("assets/ui/{}.png", name));
    let tex = load_texture(&path).await.unwrap();
    tex.set_filter(FilterMode::Linear);
    tex
}

async fn load_ui_set() -> Ui {
    let mut names: Vec<String> = Vec::new();
    for b in [
        "Play",
        "HighScores",
        "Settings",
        "Help",
        "Arcade",
        "Survival",
        "Back",
        "Local",
        "Global",
    ] {
        names.push(format!("button{}", b));
        names.push(format!("button{}Down", b));
    }
    for label in [
        "labelTitle",
        "labelSelectMode",
        "labelSelectWorld",
        "labelSelectStage",
        "labelLocalArcadeScores",
        "labelGlobalArcadeScores",
        "labelLocalSurvivalScores",
        "labelGlobalSurvivalScores",
        "labelEnterName",
    ] {
        names.push(label.to_owned());
    }
    for world in 1..=6 {
        names.push(format!("buttonArcade{}", world));
        if world > 1 {
            names.push(format!("buttonArcade{}Locked", world));
        }
        for stage in 1..=5 {
            names.push(format!("buttonStage{}.{}", world, stage));
            if stage > 1 {
                names.push(format!("buttonStage{}.{}.Locked", world, stage));
            }
        }
    }
    let mut ui = Ui::new();
    for name in names {
        let tex = load_ui(&name).await;
        ui.insert(name, tex);
    }
    ui
}

async fn load_menu_assets() -> MenuAssets {
    // MB_BG_BASE / MB_BG_DECAL_TEX override the pair while matching the
    // emulator frame (the original loads space4deep + fogRed).
    let base = std::env::var("MB_BG_BASE").unwrap_or_else(|_| "space4deep".to_owned());
    let decal = std::env::var("MB_BG_DECAL_TEX").unwrap_or_else(|_| "fogRed".to_owned());
    let menu = MenuAssets {
        space: load_texture_file(&base).await,
        fog: load_texture_file(&decal).await,
        horizon: load_ui("horizon").await,
        white: Texture2D::from_rgba8(1, 1, &[255, 255, 255, 255]),
    };
    for tex in [&menu.space, &menu.fog] {
        tex.set_filter(FilterMode::Linear);
    }
    menu
}

/// `Global::BACK_BUTTON_X/Y`: the back arrow sits at (2, 2).
const BACK_XY: f32 = 2.0;

fn button(ui: &Ui, up: &str, down: &str, x: f32, y: f32, w: f32, h: f32, event: u8) -> MenuButton {
    MenuButton {
        up: ui[up].clone(),
        down: ui[down].clone(),
        rect: Rect::new(x, y, w, h),
        event,
    }
}

/// Builds a menu screen with the original's layout (rects and events from
/// the screen constructors in the iOS binary).
fn build_menu(kind: MenuKind, ui: &Ui, progress: &Progress, fade_backdrop: bool) -> MenuScreen {
    let back = |event| {
        button(
            ui,
            "buttonBack",
            "buttonBackDown",
            BACK_XY,
            BACK_XY,
            34.0,
            34.0,
            event,
        )
    };
    match kind {
        MenuKind::Main => MenuScreen::new(
            ui["labelTitle"].clone(),
            15.0,
            vec![
                button(
                    ui,
                    "buttonPlay",
                    "buttonPlayDown",
                    160.0,
                    176.0,
                    160.0,
                    128.0,
                    0,
                ),
                button(
                    ui,
                    "buttonHighScores",
                    "buttonHighScoresDown",
                    16.0,
                    176.0,
                    128.0,
                    128.0,
                    1,
                ),
                button(
                    ui,
                    "buttonSettings",
                    "buttonSettingsDown",
                    336.0,
                    176.0,
                    127.0,
                    57.0,
                    2,
                ),
                button(
                    ui,
                    "buttonHelp",
                    "buttonHelpDown",
                    336.0,
                    246.0,
                    127.0,
                    57.0,
                    3,
                ),
            ],
            fade_backdrop,
        ),
        MenuKind::Mode => MenuScreen::new(
            ui["labelSelectMode"].clone(),
            0.0,
            vec![
                button(
                    ui,
                    "buttonArcade",
                    "buttonArcadeDown",
                    47.0,
                    118.0,
                    175.0,
                    128.0,
                    0,
                ),
                button(
                    ui,
                    "buttonSurvival",
                    "buttonSurvivalDown",
                    258.0,
                    118.0,
                    175.0,
                    128.0,
                    1,
                ),
                back(2),
            ],
            fade_backdrop,
        ),
        MenuKind::World => {
            // Columns at 30 / 176.5 / 320 (the middle one 127 wide), rows at 55 / 185.
            let slots = [
                (30.0, 55.0, 130.0),
                (176.5, 54.0, 127.0),
                (320.0, 55.0, 130.0),
                (30.0, 185.0, 130.0),
                (176.5, 185.0, 127.0),
                (320.0, 185.0, 130.0),
            ];
            let mut buttons = Vec::new();
            for (i, (x, y, w)) in slots.into_iter().enumerate() {
                let world = i + 1;
                let unlocked = i == 0 || progress.unlocked >= i * 5;
                let name = if unlocked {
                    format!("buttonArcade{}", world)
                } else {
                    format!("buttonArcade{}Locked", world)
                };
                buttons.push(button(
                    ui,
                    &name,
                    &name,
                    x,
                    y,
                    w,
                    114.0,
                    if unlocked { world as u8 } else { 0 },
                ));
            }
            buttons.push(back(7));
            MenuScreen::new(ui["labelSelectWorld"].clone(), -9.0, buttons, fade_backdrop)
        }
        MenuKind::Stage(world) => {
            let slots = [
                (30.0, 55.0),
                (176.5, 54.0),
                (320.0, 55.0),
                (100.0, 185.0),
                (250.0, 185.0),
            ];
            let mut buttons = Vec::new();
            for (i, (x, y)) in slots.into_iter().enumerate() {
                let stage = i + 1;
                let unlocked = i == 0 || progress.unlocked >= world * 5 + i;
                let name = if unlocked {
                    format!("buttonStage{}.{}", world + 1, stage)
                } else {
                    format!("buttonStage{}.{}.Locked", world + 1, stage)
                };
                buttons.push(button(
                    ui,
                    &name,
                    &name,
                    x,
                    y,
                    127.0,
                    121.0,
                    if unlocked { stage as u8 } else { 0 },
                ));
            }
            buttons.push(back(6));
            MenuScreen::new(ui["labelSelectStage"].clone(), -9.0, buttons, fade_backdrop)
        }
        // HighScoresSelectScreen: the same two-choice layout as PlayScreen.
        MenuKind::ScoresSelect => MenuScreen::new(
            ui["labelSelectMode"].clone(),
            0.0,
            vec![
                button(ui, "buttonArcade", "buttonArcadeDown", 47.0, 118.0, 175.0, 128.0, 0),
                button(ui, "buttonSurvival", "buttonSurvivalDown", 258.0, 118.0, 175.0, 128.0, 1),
                back(2),
            ],
            fade_backdrop,
        ),
        // HighScoresScreen: the mode's label, the rows (drawn by `scores`),
        // and the Local/Global tabs.
        MenuKind::ScoresTable(mode, global) => {
            let label = match (mode, global) {
                (0, false) => "labelLocalArcadeScores",
                (0, true) => "labelGlobalArcadeScores",
                (1, false) => "labelLocalSurvivalScores",
                _ => "labelGlobalSurvivalScores",
            };
            MenuScreen::new(
                ui[label].clone(),
                0.0,
                vec![
                    button(ui, "buttonLocal", "buttonLocalDown", 16.0, 258.0, 126.0, 54.0, 1),
                    button(ui, "buttonGlobal", "buttonGlobalDown", 338.0, 258.0, 126.0, 54.0, 2),
                    back(6),
                ],
                fade_backdrop,
            )
        }
    }
}

/// Whether a game starts with the tutorial: the original ran it before
/// World 1 Stage 1 and survival until help had been seen; the port runs it
/// there while the Options screen's Tutorial option is on.
fn starts_with_tutorial(settings: &Settings, world: usize, stage: usize) -> bool {
    settings.tutorial && ((world == 0 && stage == 1) || world == SURVIVAL)
}

/// The screen a menu event leads to (`handleEvent` of each screen class).
fn menu_event(kind: MenuKind, event: u8) -> Option<Next> {
    match (kind, event) {
        (MenuKind::Main, 0) => Some(Next::Menu(MenuKind::Mode)),
        // SETTINGS opens the port's Options screen; HELP its Controls page.
        (MenuKind::Main, 2) => Some(Next::Options(OptionsPage::Main)),
        (MenuKind::Main, 3) => Some(Next::Options(OptionsPage::Controls)),
        (MenuKind::Main, 1) => Some(Next::Menu(MenuKind::ScoresSelect)),
        (MenuKind::ScoresSelect, 0) => Some(Next::Menu(MenuKind::ScoresTable(0, false))),
        (MenuKind::ScoresSelect, 1) => Some(Next::Menu(MenuKind::ScoresTable(1, false))),
        (MenuKind::ScoresSelect, 2) => Some(Next::Menu(MenuKind::Main)),
        (MenuKind::ScoresTable(mode, _), 1) => Some(Next::Menu(MenuKind::ScoresTable(mode, false))),
        (MenuKind::ScoresTable(mode, _), 2) => Some(Next::Menu(MenuKind::ScoresTable(mode, true))),
        (MenuKind::ScoresTable(..), 6) => Some(Next::Menu(MenuKind::ScoresSelect)),
        (MenuKind::Mode, 0) => Some(Next::Menu(MenuKind::World)),
        (MenuKind::Mode, 1) => Some(Next::Game(SURVIVAL, 1)),
        (MenuKind::Mode, 2) => Some(Next::Menu(MenuKind::Main)),
        (MenuKind::World, 7) => Some(Next::Menu(MenuKind::Mode)),
        (MenuKind::World, w @ 1..=6) => Some(Next::Menu(MenuKind::Stage(w as usize - 1))),
        (MenuKind::Stage(_), 6) => Some(Next::Menu(MenuKind::World)),
        (MenuKind::Stage(world), s @ 1..=5) => Some(Next::Game(world, s as usize)),
        _ => None,
    }
}

